// src/utils/crypto.js
const crypto = require('crypto');

const ALGORITHM = 'aes-256-gcm';
// We expect a 64-character hex string in the .env file (32 bytes)
const KEY = Buffer.from(process.env.ENCRYPTION_KEY, 'hex');

if (KEY.length !== 32) {
  console.error('❌ ENCRYPTION_KEY must be exactly 32 bytes (64 hex characters).');
  process.exit(1);
}

/**
 * Encrypts a plain text string (e.g., M-Pesa Secret Key)
 * @param {string} text 
 * @returns {string} Format: "iv:authTag:encryptedData" (all hex)
 */
exports.encrypt = (text) => {
  if (!text) return null;
  
  const iv = crypto.randomBytes(16);
  const cipher = crypto.createCipheriv(ALGORITHM, KEY, iv);
  
  let encrypted = cipher.update(text, 'utf8', 'hex');
  encrypted += cipher.final('hex');
  
  const authTag = cipher.getAuthTag().toString('hex');
  
  // Combine IV, Auth Tag, and Encrypted Data
  return `${iv.toString('hex')}:${authTag}:${encrypted}`;
};

/**
 * Decrypts a string generated by the encrypt function
 * @param {string} encryptedData Format: "iv:authTag:encryptedData"
 * @returns {string} The original plain text
 */
exports.decrypt = (encryptedData) => {
  if (!encryptedData) return null;

  const parts = encryptedData.split(':');
  if (parts.length !== 3) throw new Error('Invalid encrypted data format');

  const [ivHex, authTagHex, encryptedHex] = parts;

  const iv = Buffer.from(ivHex, 'hex');
  const authTag = Buffer.from(authTagHex, 'hex');
  
  const decipher = crypto.createDecipheriv(ALGORITHM, KEY, iv);
  decipher.setAuthTag(authTag);

  let decrypted = decipher.update(encryptedHex, 'hex', 'utf8');
  decrypted += decipher.final('utf8');

  return decrypted;
};